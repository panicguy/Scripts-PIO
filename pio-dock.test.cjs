assert.equal(EGGS.length,4);
assert.equal(inspect(initialState()).command,undefined);
assert.equal(inspect(applyState(initialState(),{items:{70091:1}})).command,undefined);
const state=applyState(initialState(),snapshot());
assert.deepEqual(inspect(state).command,{t:'chocadeira.colocar',slot:0,ovo:'p2'});
assert.equal(inspect(state,'best-first').command.ovo,'p3');
