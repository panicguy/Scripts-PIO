const assert=require('node:assert/strict');
const fs=require('node:fs');
const {EGGS,actorOf,initialState,applyState,inspect,createEngine}=require('./pio-dock.user.js');
const empty={total:1,ovos:[]};
const snapshot=(items={70091:2,70092:2},chocadeira=empty)=>({items,chocadeira});
